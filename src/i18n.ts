export function localizeBackend(text: string): string {
  if (locale !== "en") return text;
  const exact = EXACT_BACKEND[text];
  if (exact) return exact;
  for (const [prefix, next] of PREFIX_BACKEND) {
    if (text.startsWith(prefix)) return next + text.slice(prefix.length);
  }
  const rules: [RegExp, (match: RegExpMatchArray) => string][] = [
    [/^已连通，发现 (\d+) 个模型$/, (match) => `Connected. Found ${match[1]} models.`],
    [/^探测失败 (\d+): ([\s\S]*)$/, (match) => `Probe failed ${match[1]}: ${match[2]}`],
    [/^模型接口返回 (\d+): ([\s\S]*)$/, (match) => `The model endpoint returned ${match[1]}: ${match[2]}`],
    [/^无法读取 (.+): ([\s\S]*)$/, (match) => `Could not read ${match[1]}: ${match[2]}`],
    [/^模拟现金不足：需要 (.+)，可用 (.+)$/, (match) => `Not enough paper cash: need ${match[1]}, available ${match[2]}.`],
    [/^模拟账户里没有 (.+)$/, (match) => `The paper account has no ${match[1]}.`],
    [/^持仓不足：持有 (.+)，要卖 (.+)$/, (match) => `Not enough to sell: holding ${match[1]}, selling ${match[2]}.`],
    [/^没有找到 (.+)$/, (match) => `Nothing found for ${match[1]}.`],
    [/^没有名为 (.+) 的技能$/, (match) => `No skill named ${match[1]}.`],
    [/^找到多只，请用 secid 指定一只：\n([\s\S]*)$/, (match) => `Several matches. Specify one with a secid:\n${match[1]}`],
    [/^买入数量需要是 (.+) 的整数倍$/, (match) => `The buy quantity must be a multiple of ${match[1]}.`],
    [/^行情接口返回 (\d+)$/, (match) => `The quote endpoint returned ${match[1]}.`],
    [/^原文出现了 (\d+) 次。请扩大上下文，或设置 replace_all$/, (match) => `That text appears ${match[1]} times. Add more context, or set replace_all.`],
  ];
  for (const [pattern, format] of rules) {
    const match = text.match(pattern);
    if (match) return format(match);
  }
  return text;
}
