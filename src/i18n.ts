const tables: Record<Locale, { [K in MessageKey]: string }> = { zh, en };

let locale: Locale = readLocale();
const listeners = new Set<() => void>();

function readLocale(): Locale {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === "en" || saved === "zh") return saved;
  } catch {
    // Keep the Chinese interface when storage is unavailable.
  }
  return "zh";
}

function applyLang(next: Locale) {
  if (typeof document !== "undefined") document.documentElement.lang = next === "zh" ? "zh-CN" : "en";
}

applyLang(locale);

export function getLocale(): Locale {
  return locale;
}

let langFrame = 0;

export function setLocale(next: Locale) {
  if (next !== "zh" && next !== "en") return;
  if (next === locale) return;
  locale = next;
  try {
    localStorage.setItem(KEY, next);
  } catch {
    // The choice still applies until the window closes.
  }
  for (const listener of listeners) listener();
  if (typeof requestAnimationFrame !== "function") {
    applyLang(next);
    return;
  }
  cancelAnimationFrame(langFrame);
  langFrame = requestAnimationFrame(() => applyLang(locale));
}

export function subscribeLocale(listener: () => void) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  let text: string = tables[locale][key] ?? zh[key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}

